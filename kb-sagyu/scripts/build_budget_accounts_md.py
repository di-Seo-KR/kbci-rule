    for name, r in leaf:
        path = ' > '.join(x for x in (r['관'], r['항'], r['목'], r['절']) if x)
        desc = f' — {r["취급내용"]}' if r['취급내용'] else ''
        tag = '' if r['세과목'] else ' (세과목 없음, 상위 단위 집행)'
        L.append(f'- `{name}` → {path} ({r["집행구분"] or "구분 없음"}) [No. {r["no"]}]{desc}{tag}')
    L.append('')

    # 동명 과목 (등장 블록 기준: 같은 이름의 절이 표에서 두 번 이상 새로 시작되면 동명으로 본다)
    L.append('## 3. 동명(同名) 과목 — 매핑 시 혼동 주의')
    L.append('')
    jeol_blocks = collections.OrderedDict()
    prev = None
    for r in rows:
        key = (r['관'], r['항'], r['목'], r['절'])
        if r['절'] and key != prev:
            jeol_blocks.setdefault(r['절'], []).append((r['no'], ' > '.join((r['관'], r['항'], r['목']))))
        prev = key
    se_occ = collections.OrderedDict()
    for r in rows:
        if r['세과목']:
            se_occ.setdefault(r['세과목'], []).append((r['no'], ' > '.join((r['관'], r['항'], r['목'], r['절']))))
    L.append('| 구분 | 명칭 | 등장 위치 (No. — 상위 경로) |')
    L.append('|---|---|---|')
    for name, occ in jeol_blocks.items():
        if len(occ) > 1:
            L.append(f'| 절 | {name} | ' + ' / '.join(f'No. {n} — {p}' for n, p in occ) + ' |')
    for name, occ in se_occ.items():
        if len(occ) > 1:
            L.append(f'| 세과목 | {name} | ' + ' / '.join(f'No. {n} — {p}' for n, p in occ) + ' |')
    L.append('')
    L.append('목 이름을 절·세과목이 그대로 물려받는 경우(예: 여비교통비 > 여비교통비)는 단일 계층 관행이므로 위 표에서 제외했다.')
    L.append('')

    L.append(NOTES)
    return '\n'.join(L), rows


