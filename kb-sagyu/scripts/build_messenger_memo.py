        """여러 줄에 걸친 ⟪…⟫ 를 줄 단위로 닫아 준다(단락마다 색이 끊기지 않도록)."""
        out, depth = [], 0
        for ln in text.split('\n'):
            line = ('⟪' if depth else '') + ln
            depth += ln.count('⟪') - ln.count('⟫')
            if depth: line += '⟫'
            out.append(line)
        return out

